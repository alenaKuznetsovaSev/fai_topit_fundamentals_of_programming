import math

# ============================================================
# Эксперимент A. int и арифметические операторы
# ============================================================
x = 17
y = 5

print("=== Эксперимент A ===")
print(f"x + y  = {x + y}  (тип: {type(x + y).__name__})")
print(f"x - y  = {x - y}  (тип: {type(x - y).__name__})")
print(f"x * y  = {x * y}  (тип: {type(x * y).__name__})")
print(f"x / y  = {x / y}  (тип: {type(x / y).__name__})")
print(f"x // y = {x // y}   (тип: {type(x // y).__name__})")
print(f"x % y  = {x % y}   (тип: {type(x % y).__name__})")
print(f"x ** y = {x ** y} (тип: {type(x ** y).__name__})")

# ============================================================
# Эксперимент B. Большие целые числа
# ============================================================
print("\n=== Эксперимент B ===")
big = 2 ** 1000
print(f"2 ** 1000 = {big}")
print(f"Тип: {type(big).__name__}, количество цифр: {len(str(big))}")

# ============================================================
# Эксперимент C. float
# ============================================================
print("\n=== Эксперимент C ===")
result = 0.1 + 0.2
print(f"0.1 + 0.2           = {result}")
print(f"result == 0.3       = {result == 0.3}")
print(f"result - 0.3        = {result - 0.3}")
print(f"math.isclose(res,0.3)= {math.isclose(result, 0.3)}")

# ============================================================
# Эксперимент D. bool, complex и явное преобразование типов
# ============================================================
print("\n=== Эксперимент D ===")
print(f'int("42")      = {int("42")}       (тип: {type(int("42")).__name__})')
print(f'float("3.14")  = {float("3.14")}     (тип: {type(float("3.14")).__name__})')
print(f'str(2026)      = "{str(2026)}"       (тип: {type(str(2026)).__name__})')
print(f"bool(0)        = {bool(0)}")
print(f"bool(-1)       = {bool(-1)}")
print(f'bool("")       = {bool("")}')
print(f'bool("False")  = {bool("False")}')

c = complex(2, -3)
print(f"complex(2, -3)   = {c} (тип: {type(c).__name__})")
print(f"  действительная часть: {c.real}")
print(f"  мнимая часть:         {c.imag}")