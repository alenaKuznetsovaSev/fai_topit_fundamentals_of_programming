# Прогноз результатов сравнений:
# a == b: True  (значения одинаковые, оба 1000)
# a is b: True  (b = a означает, что b ссылается на тот же объект)
# a == c: True  (значения одинаковые, оба 1000)
# a is c: False (c создан заново через int(), это другой объект,
#                так как 1000 вне кеша малых целых [-5, 256])

a = 105
b = a
c = int("105")

print("Типы:", type(a), type(b), type(c))
print("Идентификаторы:", id(a), id(b), id(c))
print("a == b:", a == b)
print("a is b:", a is b)
print("a == c:", a == c)
print("a is c:", a is c)