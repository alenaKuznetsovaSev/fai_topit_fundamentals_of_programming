import gc
import sys

# ============================================================
# Эксперимент 1. Цикл из двух списков
# ============================================================
print("=== Эксперимент 1: цикл из двух списков ===\n")

first = []
second = []
first.append(second)
second.append(first)

print(f"first ссылается на second: {first[0] is second}")
print(f"second ссылается на first: {second[0] is first}")
print("Оба списка ссылаются друг на друга — образовался цикл.")

# Запоминаем идентификаторы, чтобы потом проверить, что объекты удалены
id_first = id(first)
id_second = id(second)
print(f"\nЗапомненные id: first={id_first}, second={id_second}")

# ============================================================
# Состояние сборщика мусора
# ============================================================
print("\n--- Состояние gc ---")
print(f"Автоматический сборщик включён: {gc.isenabled()}")
print(f"Пороги поколений: {gc.get_threshold()}")
print(f"Текущие счётчики поколений: {gc.get_count()}")
print(f"Статистика по поколениям:")
for i, stats in enumerate(gc.get_stats()):
    print(f"  Поколение {i}: collections={stats['collections']}, "
          f"collected={stats['collected']}, uncollectable={stats['uncollectable']}")

# ============================================================
# Удаляем внешние ссылки
# ============================================================
print("\n--- Удаляем имена first и second ---")
del first
del second
# Имена удалены. Но объекты всё ещё живы — они ссылаются друг на друга.
# print(f"{sys.getrefcount(first)}, {sys.getrefcount(second)}") # -- error: is not defined
# Счётчик ссылок каждого из них = 1 (ссылка от другого списка).
# Обычный подсчёт ссылок их НЕ удалит.

# Запускаем ручной сбор
print("\n--- Запускаем gc.collect() ---")
collected = gc.collect()
print(f"Сборщик мусора собрал объектов: {collected}")
print("Цикл распознан как недостижимый и удалён.")

# ============================================================
# Дополнительный эксперимент: отключаем автоматический gc
# ============================================================
print("\n=== Дополнительный эксперимент: ручной gc ===\n")

gc.disable()
print(f"Автоматический сборщик отключён: {not gc.isenabled()}")

# Создаём несколько циклических структур
cycles = []
for i in range(5):
    a = [f"cycle_{i}"]
    b = [a]
    a.append(b)
    cycles.append(a)

print(f"Создано 5 циклических структур.")
print(f"Счётчики поколений: {gc.get_count()}")

# Удаляем внешние ссылки
del cycles
print("Внешние ссылки удалены. Объекты висят в памяти.")

# Ручной сбор
print("\n--- Ручной gc.collect() ---")
collected = gc.collect()
print(f"Собрано объектов: {collected}")

# Восстанавливаем автоматический сбор
gc.enable()
print(f"\nАвтоматический сборщик восстановлен: {gc.isenabled()}")

# ============================================================
# Практическая задача: граф из словарей
# ============================================================
print("\n=== Практическая задача: граф ===\n")

# Создаём граф: 3 узла в цикле + 1 независимый
node_a = {"name": "A"}
node_b = {"name": "B"}
node_c = {"name": "C"}
node_d = {"name": "D (независимый)"}

# Цикл: A → B → C → A
node_a["next"] = node_b
node_b["next"] = node_c
node_c["next"] = node_a

print("Схема графа:")
print("  A → B → C → A  (цикл)")
print("  D              (независимый)")
print(f"\nid(node_a) = {id(node_a)}")
print(f"id(node_d) = {id(node_d)}")

# Запоминаем id независимого узла
id_d = id(node_d)

# Удаляем внешние ссылки на циклические узлы
del node_a
del node_b
del node_c

# node_d оставляем!
print("\nУдалили node_a, node_b, node_c. node_d оставили.")

# Запускаем сбор
collected = gc.collect()
print(f"Собрано объектов: {collected}")
print("Должно быть: 3 словаря цикла + 3 ссылки next = 6 объектов")

# Проверяем, что независимый узел жив
print(f"\nnode_d всё ещё доступен: {node_d}")
print(f"id(node_d) не изменился: {id(node_d) == id_d}")