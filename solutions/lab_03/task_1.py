"""
Классификация результатов студента.
Программа определяет уровень результата с учётом типа работы и пропусков.
"""

import sys

# ============================================================
# Ввод данных
# ============================================================
score = int(input("Результат студента (0-100): "))
work_type = input("Тип работы (exam/project/practice): ")
absences = int(input("Количество пропущенных занятий (0-5): "))

# ============================================================
# Часть 1. Проверка диапазонов (guard clause)
# ============================================================
if not (0 <= score <= 100):
    print(f"Ошибка: результат {score} вне допустимого диапазона [0, 100].")
    sys.exit(1)

if not (0 <= absences <= 5):
    print(f"Ошибка: количество пропусков {absences} вне допустимого диапазона [0, 5].")
    sys.exit(1)

# ============================================================
# Часть 2. Определение уровня результата
# ============================================================
if score >= 90:
    level = "отличный"
elif score >= 75:
    level = "хороший"
elif score >= 60:
    level = "удовлетворительный"
else:
    level = "недостаточный"

# Понижение уровня при пропусках
if absences > 3 and level != "недостаточный":
    downgrade = {
        "отличный": "хороший",
        "хороший": "удовлетворительный",
        "удовлетворительный": "недостаточный",
    }
    level = downgrade[level]

# ============================================================
# Часть 3. Сопоставление с образцом (match/case)
# ============================================================
match work_type:
    case "exam":
        work_description = "экзаменационная работа"
    case "project":
        work_description = "проектная работа"
    case "practice":
        work_description = "практическая работа"
    case _:
        work_description = "неизвестный тип работы"

# ============================================================
# Вывод результата
# ============================================================
print(f"\nРезультат: {score} баллов")
print(f"Тип работы: {work_type} ({work_description})")
print(f"Пропуски: {absences}")
print(f"Итоговый уровень: {level}")

# ============================================================
# Практическое расширение: обработка списка записей
# ============================================================
print("\n" + "=" * 50)
print("ОБРАБОТКА СПИСКА СТУДЕНТОВ")
print("=" * 50)

records = [
    (95, "exam", 1),
    (85, "project", 4),      # пропуски > 3 → понижение
    (72, "practice", 0),
    (58, "exam", 2),
    (90, "project", 5),      # пропуски > 3 → понижение
    (60, "practice", 3),
    (75, "exam", 0),
    (45, "project", 1),
    (88, "practice", 4),     # пропуски > 3 → понижение
    (100, "exam", 0),
]

# Счётчики уровней
count_excellent = 0
count_good = 0
count_satisfactory = 0
count_insufficient = 0

downgrade = {
            "отличный": "хороший",
            "хороший": "удовлетворительный",
            "удовлетворительный": "недостаточный",
        }
for score_val, work_type_val, absences_val in records:
    # Определяем уровень (та же логика, что и выше)
    if score_val >= 90:
        lvl = "отличный"
    elif score_val >= 75:
        lvl = "хороший"
    elif score_val >= 60:
        lvl = "удовлетворительный"
    else:
        lvl = "недостаточный"

    if absences_val > 3 and lvl != "недостаточный":

        lvl = downgrade[lvl]

    # Считаем по уровням
    match lvl:
        case "отличный":
            count_excellent += 1
        case "хороший":
            count_good += 1
        case "удовлетворительный":
            count_satisfactory += 1
        case _:
            count_insufficient += 1

    print(f"  {score_val:3d} баллов, {work_type_val:8s}, пропусков: {absences_val} → {lvl}")

print("\nИтоговая сводка:")
print(f"  Отличный:          {count_excellent}")
print(f"  Хороший:           {count_good}")
print(f"  Удовлетворительный:{count_satisfactory}")
print(f"  Недостаточный:     {count_insufficient}")
print(f"  Всего записей:     {len(records)}")